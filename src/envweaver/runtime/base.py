from typing import Protocol

from ..models import Instance, RuntimeRef


class RuntimeBackend(Protocol):
    def start(self, ref: RuntimeRef) -> Instance: ...
    def exec(self, instance: Instance, command: str, cwd: str | None, timeout: float): ...
    def upload(self, instance: Instance, local_path: str, remote_path: str): ...
    def download(self, instance: Instance, remote_path: str, local_path: str): ...
    def save(self, instance: Instance, name: str) -> RuntimeRef: ...
    def close(self, instance: Instance): ...
